<?php
/**
 * PostgreSQL database adapter for Magento
 */
namespace Horobyna\Db\Ddl;

use Magento\Framework\DB\Ddl\Table;

/**
 * Sequence tables (sales_sequence: sequence_order_1, ...) with an identity column
 *
 * The core class writes MySQL DDL (AUTO_INCREMENT, UNSIGNED, ENGINE) that is run as raw SQL. Unsigned integers
 * are widened, as elsewhere in the adapter.
 */
class Sequence extends \Magento\Framework\DB\Ddl\Sequence
{
    /**
     * Widened types of unsigned integer columns
     */
    private const UNSIGNED_TYPES = [
        Table::TYPE_SMALLINT => Table::TYPE_INTEGER,
        Table::TYPE_INTEGER  => Table::TYPE_BIGINT,
    ];

    /**
     * @inheritDoc
     */
    public function getCreateSequenceDdl(
        $name,
        $startNumber = 1,
        $columnType = Table::TYPE_INTEGER,
        $unsigned = true
    ) {
        if ($unsigned) {
            $columnType = self::UNSIGNED_TYPES[$columnType] ?? $columnType;
        }

        return sprintf(
            'CREATE TABLE %s (sequence_value %s NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH %d),'
            . ' PRIMARY KEY (sequence_value))',
            $name,
            $columnType,
            $startNumber
        );
    }
}
